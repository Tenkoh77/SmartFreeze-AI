"""Write Python reference outputs that the Kotlin unit tests must reproduce.

parity_fixtures.json contains raw samples (exactly as the phone would record them),
the feature vectors computed by features/engineering.py, and the anomaly scores
and classifications computed by ReferenceForest on the exported bundle.
Missing values are written as JSON null.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pandas as pd

from ..features.engineering import compute_session_features
from .reference_scorer import ReferenceForest

_RAW_FIELDS = ["timestamp_ms", "interval_s", "mem_total_bytes", "mem_avail_bytes", "mem_threshold_bytes",
               "low_memory", "battery_level_pct", "is_charging", "thermal_status", "thermal_headroom",
               "battery_temp_c", "storage_total_bytes", "storage_avail_bytes"]


def _clean(v):
    if v is None:
        return None
    if isinstance(v, (np.integer,)):
        return int(v)
    v = float(v)
    return None if not math.isfinite(v) else v


def write_parity_fixtures(clean_df: pd.DataFrame, bundle: dict, out_path: Path,
                          max_sessions: int = 3, max_rows_per_session: int = 240) -> dict:
    window = int(bundle["window_seconds"])
    general = ReferenceForest(bundle["models"]["general"])
    sessions = []
    for sid, sess in list(clean_df.groupby("session_id", sort=False))[:max_sessions]:
        sess = sess.sort_values("timestamp_ms").head(max_rows_per_session)
        feats = compute_session_features(sess, window)
        scores = general.score_many(feats)
        sessions.append({
            "session_id": str(sid),
            "samples": [{k: _clean(r[k]) for k in _RAW_FIELDS} for r in sess.to_dict("records")],
            "features": [[_clean(v) for v in row] for row in feats],
            "scores": [float(s) for s in scores],
            "anomalous": [bool(s >= general.threshold) for s in scores],
        })
    payload = {
        "description": "Python reference outputs for Kotlin parity tests. Generated by smartfreeze_ml.pipeline.",
        "model_version": bundle["model_version"],
        "window_seconds": window,
        "feature_tolerance": 1e-9,
        "score_tolerance": 1e-9,
        "sessions": sessions,
    }
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, separators=(",", ":"))
    return payload
